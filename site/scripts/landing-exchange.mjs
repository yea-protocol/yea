/**
 * Records the landing's example exchange from the real core and writes it to
 * site/.vitepress/theme/components/landing/exchange.ts, which the page renders before the
 * core loads in the browser (and without JavaScript). Run it after `npm run build`, with a
 * Node that strips types (22.18+): node site/scripts/landing-exchange.mjs
 *
 * `record()` is also what the drift test runs, to check the file still matches the core.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const LANDING = '../.vitepress/theme/components/landing';

/** Everything the page shows from one run: the slip, the policy and each step's Lens. */
export async function record(now = Date.now()) {
  const sdk = await import('../../ts/dist/index.js');
  const { shop } = await import('../../ts/dist/examples/shop.js');
  const { landingCaveats, policySentence } = await import(
    `${LANDING}/policy.ts`
  );
  const { Session, tomorrow } = await import(`${LANDING}/session.ts`);
  const { receiptView, slipView, spendOf, undoneView } = await import(
    `${LANDING}/slip-view.ts`
  );
  const issuedAt = Math.floor(now / 1000);
  const caveats = landingCaveats(issuedAt);
  const session = await Session.start(sdk, shop, caveats);
  const waiting = await session.propose(tomorrow(now));
  const done = await session.approve(waiting);
  const undone = await session.undo(done.receipt.id);

  return {
    params: waiting.params,
    spend: spendOf(waiting.proposal),
    policy: {
      sentence: policySentence(caveats, issuedAt),
      caveats: caveats.map((c) => JSON.stringify(c)),
      grant: session.grant,
    },
    slip: slipView(sdk, waiting.proposal, waiting.consent, waiting.reason),
    receipt: receiptView(done.receipt),
    undone: undoneView(undone.receipt),
    lens: {
      proposals: waiting.proposalsLens,
      consent: waiting.consentLens,
      receipt: done.lens,
      undo: undone.lens,
    },
  };
}

const HEADER = `/**
 * The landing's example exchange, recorded from the real core: the slip, the policy and
 * each step's Lens. The page renders it until the core runs in the browser.
 * Generated by site/scripts/landing-exchange.mjs; don't edit by hand.
 */
import type { ReceiptView, SlipView, UndoneView } from './slip-view';

export interface Recorded {
  params: { items: { sku: string; qty: number }[]; deliver: string };
  /** What the proposal spends, in dollars. */
  spend: number;
  policy: { sentence: string; caveats: string[]; grant: string };
  slip: SlipView;
  receipt: ReceiptView;
  undone: UndoneView;
  lens: { proposals: string; consent: string; receipt: string; undo: string };
}

export const RECORDED: Recorded = `;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL(`${LANDING}/exchange.ts`, import.meta.url);

  writeFileSync(out, `${HEADER}${JSON.stringify(await record(), null, 2)};\n`);
  console.log(`wrote ${fileURLToPath(out)}`);
}
